const { Client } = require('pg');
const { backupDatabase } = require('./backup-db');
const { URL } = require('url');

const DATABASE_URL = process.env.DATABASE_URL || 'postgresql://chithi:chithi_secret@localhost:5432/chithi_db';

/**
 * Validates whether the database connection target is a recognized safe local/test database.
 * Rejects production databases or ambiguous external endpoints.
 */
function validateTargetEnvironment(dbUrl) {
  if (process.env.NODE_ENV === 'production') {
    throw new Error('SAFETY ABORT: Synthetic test data cleanup is strictly prohibited when NODE_ENV=production.');
  }

  let parsed;
  try {
    parsed = new URL(dbUrl);
  } catch {
    throw new Error('SAFETY ABORT: Invalid DATABASE_URL connection string.');
  }

  const hostname = (parsed.hostname || '').toLowerCase();
  const dbName = (parsed.pathname || '').replace(/^\//, '').toLowerCase();

  // Explicitly reject production database names
  const dangerousDbPatterns = ['prod', 'production', 'live', 'primary'];
  if (dangerousDbPatterns.some(pat => dbName.includes(pat))) {
    throw new Error(`SAFETY ABORT: Database name "${dbName}" matches protected production naming patterns.`);
  }

  // Allowed local and test development hostnames
  const allowedHosts = ['localhost', '127.0.0.1', 'postgres', 'postgres_dev', 'host.docker.internal'];
  const isAllowedHost = allowedHosts.includes(hostname) || hostname.endsWith('.local');

  if (!isAllowedHost && process.env.ALLOW_REMOTE_TEST_DB !== 'true') {
    throw new Error(
      `SAFETY ABORT: Host "${hostname}" is not a recognized local or test database endpoint. ` +
      'Set ALLOW_REMOTE_TEST_DB=true only for isolated cloud test environments.'
    );
  }

  return { hostname, dbName };
}

/**
 * Positive Identification of Synthetic Test Accounts:
 * Matches deterministic test usernames generated by automated test runners AND
 * RFC 2606 reserved test email domains (@example.com, @example.org, @example.net, @test.local).
 * Never relies on a hardcoded allowlist or exclusion list.
 */
const SYNTHETIC_USER_REGEX =
  '^(alice|bob|cal_a|cal_b|call_a|call_b|call_c|covfix|prof_a|prof_b|media_a|media_b|stranger_c|user_a|user_b|user_c|brand_qa|integration_test|test_user|smoke_a|smoke_b)_[0-9]{8,18}$';

const SYNTHETIC_EMAIL_DOMAINS = [
  '%@example.com',
  '%@example.org',
  '%@example.net',
  '%@test.local',
  '%@chithi.test'
];

async function cleanupSyntheticTestData(options = {}) {
  const isDryRun = options.dryRun !== undefined ? options.dryRun : !process.argv.includes('--execute');
  const customDbUrl = options.databaseUrl || DATABASE_URL;

  console.log('================================================================');
  console.log(`CHITHI SYNTHETIC TEST DATA CLEANUP (${isDryRun ? 'DRY-RUN MODE' : 'EXECUTION MODE'})`);
  console.log('================================================================');

  const { hostname, dbName } = validateTargetEnvironment(customDbUrl);
  const sanitizedUrl = customDbUrl.replace(/:[^:@]+@/, ':***@');
  console.log(`Verified Target: ${sanitizedUrl}`);
  console.log(`Host: ${hostname} | Database: ${dbName} | Mode: ${isDryRun ? 'DRY-RUN (No changes will be made)' : 'LIVE EXECUTION'}\n`);

  // If in execution mode, mandatory safety backup first
  let backupInfo = null;
  if (!isDryRun) {
    if (options.skipBackup !== true) {
      console.log('[STEP 1/4] Running pre-cleanup safety backup...');
      backupInfo = await backupDatabase(customDbUrl);
      console.log(`[PASS] Safety backup confirmed: ${backupInfo.backupFilePath}\n`);
    } else {
      console.log('[STEP 1/4] Pre-cleanup backup skipped (isolated test harness)...\n');
    }
  } else {
    console.log('[STEP 1/4] Skipping backup creation (Dry-Run mode).\n');
  }

  const client = new Client({ connectionString: customDbUrl });
  await client.connect();

  try {
    // Construct positive identification query
    const emailConditions = SYNTHETIC_EMAIL_DOMAINS.map((_, i) => `email ILIKE $${i + 2}`).join(' OR ');
    const identificationSql = `
      SELECT id, created_at
      FROM users
      WHERE username ~* $1
        AND (${emailConditions})
      ORDER BY created_at ASC;
    `;

    const syntheticUsersRes = await client.query(identificationSql, [
      SYNTHETIC_USER_REGEX,
      ...SYNTHETIC_EMAIL_DOMAINS
    ]);

    const totalUsersRes = await client.query('SELECT count(*)::int as count FROM users;');
    const totalUsers = totalUsersRes.rows[0].count;
    const syntheticCount = syntheticUsersRes.rowCount;
    const legitimateCount = totalUsers - syntheticCount;

    console.log('[STEP 2/4] Positive Synthetic Account Identification Audit:');
    console.log(`  Total user accounts in database : ${totalUsers}`);
    console.log(`  Positively identified synthetic : ${syntheticCount}`);
    console.log(`  Legitimate real accounts        : ${legitimateCount}`);

    if (syntheticCount === 0) {
      console.log('\n[INFO] Zero synthetic test accounts identified. Database is already clean.');
      return { dryRun: isDryRun, totalUsers, syntheticCount: 0, deletedUsers: 0 };
    }

    const syntheticIds = syntheticUsersRes.rows.map(r => r.id);

    // Audit dependent record relationships
    const dependentStats = await client.query(`
      SELECT
        (SELECT count(*)::int FROM user_profiles WHERE user_id = ANY($1)) as profiles,
        (SELECT count(*)::int FROM user_settings WHERE user_id = ANY($1)) as settings,
        (SELECT count(*)::int FROM user_sessions WHERE user_id = ANY($1)) as sessions,
        (SELECT count(*)::int FROM conversations WHERE created_by = ANY($1)) as conversations,
        (SELECT count(*)::int FROM conversation_members WHERE user_id = ANY($1)) as conversation_members,
        (SELECT count(*)::int FROM messages WHERE sender_id = ANY($1)) as messages,
        (SELECT count(*)::int FROM posts WHERE author_id = ANY($1)) as posts,
        (SELECT count(*)::int FROM post_comments WHERE author_id = ANY($1)) as comments,
        (SELECT count(*)::int FROM post_reactions WHERE user_id = ANY($1)) as reactions,
        (SELECT count(*)::int FROM media_assets WHERE owner_id = ANY($1)) as media_assets,
        (SELECT count(*)::int FROM call_sessions WHERE caller_id = ANY($1) OR receiver_id = ANY($1)) as call_sessions,
        (SELECT count(*)::int FROM notifications WHERE user_id = ANY($1) OR actor_id = ANY($1)) as notifications;
    `, [syntheticIds]);

    const stats = dependentStats.rows[0];
    console.log('\n[STEP 3/4] Dependent Record Impact Assessment:');
    console.log(`  - user_profiles        : ${stats.profiles} records`);
    console.log(`  - user_settings        : ${stats.settings} records`);
    console.log(`  - user_sessions        : ${stats.sessions} records`);
    console.log(`  - conversations        : ${stats.conversations} records`);
    console.log(`  - conversation_members : ${stats.conversation_members} records`);
    console.log(`  - messages             : ${stats.messages} records`);
    console.log(`  - posts (Moments)      : ${stats.posts} records`);
    console.log(`  - post_comments        : ${stats.comments} records`);
    console.log(`  - post_reactions       : ${stats.reactions} records`);
    console.log(`  - media_assets         : ${stats.media_assets} records`);
    console.log(`  - call_sessions        : ${stats.call_sessions} records`);
    console.log(`  - notifications        : ${stats.notifications} records\n`);

    if (isDryRun) {
      console.log('----------------------------------------------------------------');
      console.log('[DRY-RUN COMPLETE] No database rows were modified or removed.');
      console.log('To execute this cleanup, run with the explicit flag:');
      console.log('  node apps/api/scripts/cleanup-synthetic-test-data.js --execute');
      console.log('----------------------------------------------------------------\n');
      return {
        dryRun: true,
        totalUsers,
        syntheticCount,
        dependentRecords: stats,
      };
    }

    // Execute atomic cleanup transaction
    console.log('[STEP 4/4] Executing atomic transaction for positively identified records...');
    await client.query('BEGIN');

    // 1. Clean outbox events associated with synthetic messages
    await client.query(`
      DELETE FROM outbox_events
      WHERE aggregate_id IN (
        SELECT id FROM messages WHERE sender_id = ANY($1)
      );
    `, [syntheticIds]);

    // 2. Clean messages sent by synthetic users
    await client.query(`DELETE FROM messages WHERE sender_id = ANY($1);`, [syntheticIds]);

    // 3. Clean post interactions & posts authored by synthetic users
    await client.query(`DELETE FROM post_comments WHERE author_id = ANY($1);`, [syntheticIds]);
    await client.query(`DELETE FROM post_reactions WHERE user_id = ANY($1);`, [syntheticIds]);
    await client.query(`
      DELETE FROM post_media
      WHERE post_id IN (SELECT id FROM posts WHERE author_id = ANY($1));
    `, [syntheticIds]);
    await client.query(`DELETE FROM posts WHERE author_id = ANY($1);`, [syntheticIds]);

    // 4. Clean conversations created by synthetic users
    await client.query(`DELETE FROM conversations WHERE created_by = ANY($1);`, [syntheticIds]);

    // 5. Clean media assets owned by synthetic users
    await client.query(`DELETE FROM media_assets WHERE owner_id = ANY($1);`, [syntheticIds]);

    // 6. Delete synthetic users (Foreign keys CASCADE will clean profiles, settings, sessions, call records)
    const deleteResult = await client.query(`
      DELETE FROM users WHERE id = ANY($1) RETURNING id;
    `, [syntheticIds]);

    await client.query('COMMIT');
    console.log(`[PASS] Transaction committed. Successfully removed ${deleteResult.rowCount} synthetic test accounts.\n`);

    // Verify post-cleanup integrity
    const remainingUsers = await client.query('SELECT count(*)::int as count FROM users;');
    const orphansRes = await client.query(`
      SELECT 'user_profiles' as table, count(*)::int FROM user_profiles WHERE user_id NOT IN (SELECT id FROM users)
      UNION ALL
      SELECT 'user_settings', count(*)::int FROM user_settings WHERE user_id NOT IN (SELECT id FROM users)
      UNION ALL
      SELECT 'friendships', count(*)::int FROM friendships WHERE user_low_id NOT IN (SELECT id FROM users) OR user_high_id NOT IN (SELECT id FROM users);
    `);
    const orphanCount = orphansRes.rows.reduce((acc, r) => acc + r.count, 0);

    console.log('Post-cleanup Verification:');
    console.log(`  Remaining user accounts: ${remainingUsers.rows[0].count}`);
    console.log(`  Orphan records found   : ${orphanCount}`);

    if (orphanCount === 0) {
      console.log('  ✓ 100% referential integrity verified!\n');
    }

    return {
      dryRun: false,
      deletedUsers: deleteResult.rowCount,
      remainingUsers: remainingUsers.rows[0].count,
      orphanCount
    };
  } catch (err) {
    if (!isDryRun) {
      await client.query('ROLLBACK');
      console.error('Cleanup transaction failed and was rolled back cleanly:', err.message);
    }
    throw err;
  } finally {
    await client.end();
  }
}

if (require.main === module) {
  cleanupSyntheticTestData().catch(err => {
    console.error('\nExecution halted:', err.message);
    process.exit(1);
  });
}

module.exports = { cleanupSyntheticTestData, validateTargetEnvironment };
